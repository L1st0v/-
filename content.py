FIRST_STAGE = min(STAGES)
LAST_STAGE = max(STAGES)


def get_stage(number: int) -> dict:
    """Возвращает содержимое этапа. Для неизвестного номера - заглушку."""
    return STAGES.get(
        number,
        {"title": f"Этап {number}", "paragraphs": ["Этот этап ещё не описан."]},
    )


def public_view(number: int) -> dict:
    """То, что уходит в мини-приложение. Кодовая фраза наружу не отдаётся."""
    stage = get_stage(number)
    return {
        "number": number,
        "title": stage.get("title", ""),
        "paragraphs": stage.get("paragraphs", []),
        "button": stage.get("button"),
        "game": stage.get("game"),
    }


def personal_word(number: int, position: int) -> str | None:
    """Слово, которое достаётся одному участнику на этапе с игрой.

    position - порядковый номер участника (кто раньше зашёл, у того меньше).
    Слова раздаются по кругу, поэтому при четырёх и более участниках
    вся фраза точно окажется собрана.
    """
    words = get_stage(number).get("words")
    if not words:
        return None
    return words[int(position) % len(words)]


def normalize(text: str) -> str:
    """Приводит фразу к сравнимому виду.

    Убирает регистр, знаки препинания, лишние пробелы и разницу между е и ё.
    Так участник может написать "помните вкус жижи!" и это засчитается.
    """
    lowered = (text or "").lower().replace("ё", "е")
    letters = [ch if ch.isalnum() else " " for ch in lowered]
    return " ".join("".join(letters).split())


def phrase_matches(number: int, text: str) -> bool:
    """Проверяет, совпала ли фраза, открывающая следующий этап."""
    phrase = get_stage(number).get("phrase")
    if not phrase:
        return False
    return normalize(text) == normalize(phrase)


def announcement(number: int) -> str:
    """Текст рассылки при переходе на этап number."""
    return get_stage(number).get(
        "announce", f"Начался этап {number}, откройте мини-приложение"
    )
